"""Retrieval/context ablation using sealed dense hits and real PDFs.

No remote calls. Sparse ranking reads scoped child text, never answer labels.
The window variant is scored only on its actual clipped source intervals.
"""
import argparse
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.chunking import ChunkingConfig, ChunkingEngine
from app.chunking.adapter import adapt_parse_result
from app.evaluation.literature import Pilot, load_documents, locate_evidence, Candidate, Span, evidence_metrics
from app.research.evidence import EvidenceCorpus, HybridEvidenceEngine, RetrievalOptions, VectorHit
from app.research.lexical import LexicalEvidenceRetriever
from app.research.artifacts import _quote_source, Claim
from app.research.graph import Citation


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('pilot','sources','retrieval-report','output'):
        parser.add_argument('--'+name, type=Path, required=True)
    parser.add_argument('--report-sha256', required=True)
    parser.add_argument('--source-role', action='store_true', help='Include opt-in attribution ranking')
    args = parser.parse_args()
    if hashlib.sha256(args.retrieval_report.read_bytes()).hexdigest() != args.report_sha256:
        parser.error('Retrieval report digest mismatch')
    pilot = Pilot.model_validate_json(args.pilot.read_text(encoding='utf-8'))
    parsed = load_documents(pilot,args.sources)
    corpus = EvidenceCorpus(1,tuple(ChunkingEngine().split(adapt_parse_result(parsed[p.document_id],
        document_id=p.document_id,file_name=p.file_name),ChunkingConfig(child_max_tokens=600,parent_max_tokens=1800))
        for p in pilot.papers))
    prior = json.loads(args.retrieval_report.read_text(encoding='utf-8'))
    dense_rows = {r['question_id']:r for r in prior['rows'] if r['variant']=='rag4'}
    selected = []
    for question in pilot.questions:
        hits = dense_rows[question.id]['hits'][:10]
        if any(h['id'] not in corpus.chunks or corpus.chunks[h['id']].text != h['text'] for h in hits):
            raise ValueError('Frozen candidate mismatch')
        class Replay:
            def search(self,*args):
                return [VectorHit(chunk_id=h['id'],score=h['score']) for h in hits]
        policies = ('vector-v1','lexical-fusion-v2','source-role-v3') if args.source_role else ('vector-v1','lexical-fusion-v2')
        for candidates in policies:
            retriever = Replay() if candidates=='vector-v1' else LexicalEvidenceRetriever(corpus,Replay(),
                source_role=candidates=='source-role-v3')
            for context in ('parent-floor-v2','local-window-v3'):
                bundle = HybridEvidenceEngine(corpus,retriever).search(1,question.question,RetrievalOptions(
                    document_ids=tuple(corpus.chunk_sets),context_policy=context,include_graph=False))
                # Use the same source mapper as real citation composition; no
                # semantic claim is generated by this diagnostic placeholder.
                rows = []
                for item in bundle.items:
                    citation = Citation(chunk_id=item.chunk.chunk_id,char_start=item.context_start,
                        char_end=item.context_start+len(item.text),quote=item.text)
                    locator = _quote_source(corpus,Claim(claim_id='diagnostic',document_id=item.chunk.document_id,
                        facet='method',statement='source interval only',citation=citation)).source_locator
                    candidate = Candidate(item.chunk.chunk_id,item.chunk.document_id,item.chunk.chunk_index,item.text,
                        tuple(Span(item.chunk.document_id,s.page_start,s.char_start,s.char_end) for s in locator.spans))
                    rows.append(candidate)
                selected.append((question.id,candidates,context,bundle,rows))
    # Annotation data is first read after all variants have selected evidence.
    gold = locate_evidence(pilot,parsed)
    output = {'schema':'research-retrieval-ablation-v2' if args.source_role else 'research-retrieval-ablation-v1','annotation_status':pilot.annotation_status,
        'quality_gate_passed':False,'extra_model_calls':0,'retrieval_report_sha256':args.report_sha256,
        'corpus_id':corpus.corpus_id,'max_context_chars':6000,'max_items':10,'unique_candidates':10,'rows':[],
        'limitations':['Development AI anchor set, not human semantic judgment or a holdout',
            'Dense candidates are cached top-10; lexical scores use full scoped source text',
            'Candidate/context ablation separates changes; no production default switch',
            'Source-role hints are attribution heuristics, not verified source ownership']}
    for qid,candidates,context,bundle,rows in selected:
        output['rows'].append({'question_id':qid,'candidate_policy':candidates,'context_policy':context,
            'bundle_id':bundle.bundle_id,'context_chars':bundle.context_chars,'items':[
                {'chunk_id':item.chunk.chunk_id,'start':item.context_start,'end':item.context_start+len(item.text),
                 'matched_child_ids':item.matched_child_ids,'channels':item.channels,'source_spans':[asdict(s) for s in c.spans]}
                for item,c in zip(bundle.items,rows)],**evidence_metrics(gold[qid],rows,ks=(10,))})
    variants = {}
    for r in output['rows']:
        key = r['candidate_policy']+'/'+r['context_policy']
        variants.setdefault(key,[]).append(r)
    output['variants'] = {key:{'mean_anchor_coverage':sum(r['metrics']['10']['anchor_span_recall'] for r in rows if r['metrics'])/sum(bool(r['metrics']) for r in rows),
        'complete_questions':sum(r['metrics']['10']['all_evidence_covered'] for r in rows if r['metrics']),
        'scored':sum(bool(r['metrics']) for r in rows),
        'mean_context_chars':sum(r['context_chars'] for r in rows)/len(rows)} for key,rows in variants.items()}
    output['code_sha256'] = {p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in
        [Path(__file__)]+list((Path(__file__).resolve().parents[1]/'app/research').glob('*.py'))}
    args.output.mkdir(parents=True,exist_ok=False)
    (args.output/'report.json').write_text(json.dumps(output,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(output['variants']))


if __name__=='__main__':
    main()
